"""Derive the portable native table from the public syscall declarations.

Declaration order is ABI slot order: append calls within a major version.
Existing signatures and public data layouts must also retain their ABI.
"""

import re
import sys
from pathlib import Path


def generate(header: Path, output: Path):
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", header.read_text(), flags=re.S)
    calls = re.findall(r"__syscall\s+(\w+)\s+(bp_\w+)\(([^;]*)\);", source)
    if not calls or len(calls) != len(re.findall(r"\b__syscall\b", source)):
        raise ValueError("Unsupported native API declaration")
    table = ["// Generated by tools/native_api.py; do not edit.", "#pragma once", "",
             "struct bp_api {", "\tuint32_t capabilities;"]
    wrappers = []
    initializer = []
    for result, name, args in calls:
        args = " ".join(args.split())
        names = [] if args == "void" else [
            re.fullmatch(r"[\w *]+\b(\w+)", arg.strip())[1] for arg in args.split(",")
        ]
        table.append(f"\t{result} (*{name})({args});")
        expression = f"BP_API_SYMBOL.{name}({', '.join(names)})"
        wrappers.append(f"static inline {result} {name}({args})\n{{\n\t"
                        f"{'' if result == 'void' else 'return '}{expression};\n}}")
        initializer.append(f"\t.{name} = {name},")
    table += ["};", "extern const struct bp_api BP_API_SYMBOL;", "",
              "static inline uint32_t bp_capabilities(void)", "{",
              "\treturn BP_API_SYMBOL.capabilities;", "}", "",
              "#if defined(LL_EXTENSION_BUILD) || !defined(__ZEPHYR__)",
              *wrappers, "#endif", ""]
    for name, lines in (("brickphyr_api.h", table), ("brickphyr_api.inc", initializer)):
        path = output / name
        text = "\n".join(lines) + "\n"
        if not path.exists() or path.read_text() != text:
            path.write_text(text)


if __name__ == "__main__":
    generate(*map(Path, sys.argv[1:]))
